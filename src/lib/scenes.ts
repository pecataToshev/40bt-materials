let uid = 0;

function hullPath(dir: 'l' | 'r') {
  return dir === 'r'
    ? 'M16 110 L184 110 L194 104 L176 128 L36 128 Z'
    : 'M184 110 L16 110 L6 104 L24 128 L164 128 Z';
}

function lightSvg([c, x, y, kind]: Light): string {
  const col = COL[c];
  if (kind === 'h') {
    return `<circle cx="${x}" cy="${y}" r="13" fill="#ffffff" opacity=".12"/>` +
      `<path d="M${x} ${y - 7} A7 7 0 0 0 ${x} ${y + 7} Z" fill="${COL.g}"/>` +
      `<path d="M${x} ${y - 7} A7 7 0 0 1 ${x} ${y + 7} Z" fill="${COL.r}"/>`;
  }
  let s = `<circle cx="${x}" cy="${y}" r="11" fill="${col}" opacity=".2"/>` +
    `<circle cx="${x}" cy="${y}" r="5" fill="${col}"/>`;
  if (kind === 'f') {
    for (let a = 0; a < 8; a++) {
      const r = (a * Math.PI) / 4;
      s += `<line x1="${(x + Math.cos(r) * 8).toFixed(1)}" y1="${(y + Math.sin(r) * 8).toFixed(1)}" x2="${(x + Math.cos(r) * 14).toFixed(1)}" y2="${(y + Math.sin(r) * 14).toFixed(1)}" stroke="${col}" stroke-width="1.6" stroke-linecap="round"/>`;
    }
  }
  return s;
}

export function lightsSvg(lights: Light[], hull?: 'l' | 'r', label = 'Светлини'): string {
  const id = `g${uid++}`;
  const sky = `<defs><linearGradient id="${id}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#040b12"/><stop offset="1" stop-color="#0b2233"/></linearGradient></defs>`;
  const water = `<rect x="0" y="128" width="200" height="22" fill="#0a1c2a"/><line x1="0" y1="128" x2="200" y2="128" stroke="#17384f" stroke-width="1"/>`;
  const h = hull ? `<path d="${hullPath(hull)}" fill="#122a3b" stroke="#1d3d55" stroke-width="1"/>` : '';
  return `<svg viewBox="0 0 200 140" role="img" aria-label="${label.replace(/"/g, '&quot;')}" xmlns="http://www.w3.org/2000/svg">${sky}<rect width="200" height="140" fill="url(#${id})"/>${water}${h}${lights.map(lightSvg).join('')}</svg>`;
}

export function sceneSvg(id: string): string {
  const s = scenes.find((x) => x.id === id);
  if (!s) return '';
  return lightsSvg(s.lights, s.hull, s.title);
}
